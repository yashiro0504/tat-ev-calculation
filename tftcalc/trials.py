"""몬테카를로 시행 수(``trials``) 기본값을 한곳에 모은다.

왜 필요한가(L7): 예전엔 같은 "시행 수"가 ``cli.py`` 아규먼트 기본값(1_500 / 4_000 /
20_000)과 각 라이브러리 함수 기본값(3_000 / 4_000 / 20_000)에 **서로 다르게**
하드코딩되어 있어, 어느 명령이 얼마나 정밀한지 한눈에 알 수 없었다.

값을 고를 때의 근거
-------------------
* ``FAST``      — 명령 하나가 여러 축(경제+생존+컴프)을 연속 계산하므로 낮게.
* ``REPEATED``  — 후보 수가 곱해지는 계산(컴프 랭킹, 오차 내성 스캔). 시뮬레이션
                  비용이 후보 개수만큼 배수로 든다.
* ``STANDARD``  — 한 개의 지표를 구할 때의 표준값(공개 벤치마크 재현 정밀도).
* ``HEAVY``     — 시행당 비용이 아주 낮은 시뮬레이션(부품 추첨, 라운드별 생존).

주의: 이 값은 **속도/정밀도 절충**이지 과학적 상수가 아니다. 출력에 자릿수를
과도하게 신뢰하지 말고, 민감도는 ``sensitivity`` 명령으로 직접 보라.
"""

from __future__ import annotations

#: 빠른 확인용(명령 하나가 여러 축을 연속 계산할 때).
FAST = 1_500

#: 반복 계산 — 후보 수 x 시행 (컴프 랭킹, 오차 내성 스캔).
REPEATED = 3_000

#: 표준 — 단일 지표(공개 벤치마크 재현 정밀도).
STANDARD = 4_000

#: 대량 — 시행당 비용이 아주 낮은 시뮬레이션(부품 추첨, 생존).
HEAVY = 20_000

__all__ = ["FAST", "REPEATED", "STANDARD", "HEAVY"]
